// Stages the pinned onnxruntime-web WebAssembly runtime into `public/ort/` so the
// browser loads it same-origin. No CDN is ever used by a docs example.
//
// The WebGPU entry point (`onnxruntime-web/webgpu`) references exactly the two
// asyncify artifacts below; nothing else in `dist/` is needed at runtime, so the
// remaining ~50 MiB of flavors are deliberately not copied.
//
// Usage:
//   node scripts/prepare-ort-assets.mjs           stage (idempotent)
//   node scripts/prepare-ort-assets.mjs --check   verify staged bytes match the package
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const docsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageDir = path.join(docsDir, 'node_modules', 'onnxruntime-web');
const sourceDir = path.join(packageDir, 'dist');
const outDir = path.join(docsDir, 'public', 'ort');
const manifestFile = path.join(outDir, 'manifest.json');

/** Pinned version; a mismatch is a hard failure so staged bytes never drift from the lockfile. */
const expectedVersion = '1.27.0';

/** Explicit allowlist: the asyncify runtime pair used by `onnxruntime-web/webgpu`. */
const allowlist = ['ort-wasm-simd-threaded.asyncify.mjs', 'ort-wasm-simd-threaded.asyncify.wasm'];

const check = process.argv.slice(2).includes('--check');

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

async function readPackageVersion() {
  const raw = await readFile(path.join(packageDir, 'package.json'), 'utf8').catch(() => {
    throw new Error(
      `onnxruntime-web is not installed at ${path.relative(docsDir, packageDir)}. Run pnpm install.`,
    );
  });
  const { version } = JSON.parse(raw);
  if (version !== expectedVersion) {
    throw new Error(`onnxruntime-web must stay pinned at ${expectedVersion} (found ${version}).`);
  }
  return version;
}

const version = await readPackageVersion();

const staged = [];
for (const name of allowlist) {
  const bytes = await readFile(path.join(sourceDir, name)).catch(() => {
    throw new Error(`onnxruntime-web ${version} does not contain dist/${name}.`);
  });
  staged.push({ file: name, bytes: bytes.byteLength, sha256: sha256(bytes), content: bytes });
}

const manifest = {
  description: 'Generated by scripts/prepare-ort-assets.mjs. Same-origin onnxruntime-web runtime.',
  package: 'onnxruntime-web',
  version,
  files: staged.map(({ file, bytes, sha256: hash }) => ({ file, bytes, sha256: hash })),
};
const manifestJson = `${JSON.stringify(manifest, null, 2)}\n`;

if (check) {
  const failures = [];
  const previous = await readFile(manifestFile, 'utf8').catch(() => undefined);
  if (previous !== manifestJson) failures.push(`${path.relative(docsDir, manifestFile)} is missing or stale.`);
  for (const entry of staged) {
    const actual = await readFile(path.join(outDir, entry.file)).catch(() => undefined);
    if (!actual) failures.push(`public/ort/${entry.file} is missing.`);
    else if (sha256(actual) !== entry.sha256) failures.push(`public/ort/${entry.file} does not match the pinned package.`);
  }
  if (failures.length) {
    console.error(`${failures.join('\n')}\nRun \`pnpm --filter docs ort:assets\`.`);
    process.exitCode = 1;
  } else {
    console.log(`ORT assets verified: ${staged.length} files from onnxruntime-web ${version}.`);
  }
} else {
  // Clear only this script's own output directory, never anything else under public/.
  const existing = await readdir(outDir).catch(() => []);
  for (const name of existing) await rm(path.join(outDir, name), { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  for (const entry of staged) await writeFile(path.join(outDir, entry.file), entry.content);
  await writeFile(manifestFile, manifestJson);
  const total = staged.reduce((sum, entry) => sum + entry.bytes, 0);
  console.log(
    `Staged ${staged.length} onnxruntime-web ${version} runtime files (${(total / 1024 / 1024).toFixed(1)} MiB) into public/ort/.`,
  );
}
