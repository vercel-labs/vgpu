// Stages detect-gpu's pinned benchmark tables into a same-origin public path.
// The runtime requests only the table that matches the detected vendor.
//
// Usage:
//   node scripts/prepare-prism-gpu-benchmarks.mjs
//   node scripts/prepare-prism-gpu-benchmarks.mjs --check
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const docsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageDir = path.join(docsDir, 'node_modules', '@pmndrs', 'detect-gpu');
const sourceDir = path.join(packageDir, 'dist', 'benchmarks');
const outDir = path.join(docsDir, 'public', 'prism-gpu-benchmarks');
const manifestFile = path.join(outDir, 'manifest.json');
const expectedVersion = '6.0.20';
const allowlist = [
  'd-adreno.json',
  'd-amd.json',
  'd-apple.json',
  'd-geforce.json',
  'd-intel.json',
  'd-nvidia.json',
  'd-radeon.json',
  'm-adreno.json',
  'm-apple-ipad.json',
  'm-apple.json',
  'm-intel.json',
  'm-mali-t.json',
  'm-mali.json',
  'm-nvidia.json',
  'm-powervr.json',
  'm-samsung.json',
];
const check = process.argv.slice(2).includes('--check');

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

async function packageVersion() {
  const raw = await readFile(path.join(packageDir, 'package.json'), 'utf8').catch(() => {
    throw new Error(
      `@pmndrs/detect-gpu is not installed at ${path.relative(docsDir, packageDir)}. Run pnpm install.`,
    );
  });
  const { version } = JSON.parse(raw);
  if (version !== expectedVersion) {
    throw new Error(`@pmndrs/detect-gpu must stay pinned at ${expectedVersion} (found ${version}).`);
  }
  return version;
}

const version = await packageVersion();
const available = (await readdir(sourceDir)).filter((name) => name.endsWith('.json')).sort();
if (JSON.stringify(available) !== JSON.stringify(allowlist)) {
  throw new Error(
    `@pmndrs/detect-gpu ${version} benchmark inventory changed. Review and update the explicit allowlist.`,
  );
}

const staged = [];
for (const file of allowlist) {
  const content = await readFile(path.join(sourceDir, file));
  staged.push({ file, bytes: content.byteLength, sha256: sha256(content), content });
}

const manifest = {
  description: 'Generated by scripts/prepare-prism-gpu-benchmarks.mjs. Same-origin detect-gpu data.',
  package: '@pmndrs/detect-gpu',
  version,
  files: staged.map(({ file, bytes, sha256: hash }) => ({ file, bytes, sha256: hash })),
};
const manifestJson = `${JSON.stringify(manifest, null, 2)}\n`;

if (check) {
  const failures = [];
  const previous = await readFile(manifestFile, 'utf8').catch(() => undefined);
  if (previous !== manifestJson) failures.push(`${path.relative(docsDir, manifestFile)} is missing or stale.`);
  for (const entry of staged) {
    const actual = await readFile(path.join(outDir, entry.file)).catch(() => undefined);
    if (!actual) failures.push(`public/prism-gpu-benchmarks/${entry.file} is missing.`);
    else if (sha256(actual) !== entry.sha256) {
      failures.push(`public/prism-gpu-benchmarks/${entry.file} does not match the pinned package.`);
    }
  }
  if (failures.length) {
    console.error(`${failures.join('\n')}\nRun \`pnpm --filter docs prism-gpu:assets\`.`);
    process.exitCode = 1;
  } else {
    console.log(`Prism GPU benchmarks verified: ${staged.length} files from detect-gpu ${version}.`);
  }
} else {
  const existing = await readdir(outDir).catch(() => []);
  for (const name of existing) await rm(path.join(outDir, name), { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  for (const entry of staged) await writeFile(path.join(outDir, entry.file), entry.content);
  await writeFile(manifestFile, manifestJson);
  const total = staged.reduce((sum, entry) => sum + entry.bytes, 0);
  console.log(
    `Staged ${staged.length} detect-gpu ${version} benchmark files (${(total / 1024).toFixed(1)} KiB).`,
  );
}
