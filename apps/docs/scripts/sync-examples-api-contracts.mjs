import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const docsDir = resolve(root, 'apps/docs/lib/examples-api/schemas/v1');
const cliDir = resolve(root, 'packages/vgpu/lib/examples/schemas/v1');
const names = ['discovery', 'error', 'index', 'manifest'];
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
await mkdir(cliDir, { recursive: true });
const hashes = {};
let contractFrame = 'vgpu-examples-contract/v1\0';
for (const name of names) {
  const file = `${name}.schema.json`;
  const bytes = await readFile(resolve(docsDir, file));
  hashes[file] = digest(bytes);
  contractFrame += `${Buffer.byteLength(file)}:${file}\n${bytes.byteLength}:${hashes[file]}\n`;
  await cp(resolve(docsDir, file), resolve(cliDir, file));
}
const contractSha256 = digest(contractFrame);
const output = `// Generated by apps/docs/scripts/sync-examples-api-contracts.mjs.\nexport const EXAMPLES_CONTRACT_ID = 'vgpu-examples/v1';\nexport const EXAMPLES_SCHEMA_SHA256 = '${contractSha256}';\nexport const EXAMPLES_SCHEMA_HASHES = ${JSON.stringify(hashes, null, 2)};\n`;
await writeFile(resolve(root, 'packages/vgpu/lib/examples/contracts.js'), output);
await writeFile(resolve(root, 'apps/docs/lib/examples-api/contracts.generated.ts'), output);
console.log(contractSha256);
