#!/usr/bin/env node
// Drift check: regenerates the docs manifest + thin skill router into a scratch temp dir (never touches
// the working tree) and diffs it against the committed copies — packages/vgpu/lib/generated/
// docs-manifest.generated.js and skills/vgpu. Run this in CI on every PR so a generator or *.docs.md
// change that wasn't followed by `pnpm -F @vgpu/cli generate:docs` fails with an actionable
// message, instead of silently shipping a stale router via `npx skills add vercel-labs/vgpu`.
//
// TGEIST-12 extension (Decision 4, closing line: "extender check-drift.js al target geistdocs para
// que content/docs/** commiteado no pueda driftear"). The geistdocs content tree is generated by
// generate-geistdocs.js from the same *.docs.md sources plus docs/nav.json, and it is committed, so
// it can drift like any other generated output. It is checked here, in the same never-mutate-the-tree
// style: generate into the scratch dir, diff bytes, report. The pre-existing CI pair
// ("regenerate then git diff --exit-code") could only run where writing to the working tree is
// acceptable, which is why the drift half moves here — this script is safe to run locally on a
// dirty tree, and it names the exact file plus the command to fix it.
import { mkdtempSync, readdirSync, readFileSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { generateDocs } from "./generate.js";
import { DEFAULT_CONTENT_DIR, generateGeistdocs } from "./generate-geistdocs.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../../../..");
const committedSkillDir = resolve(root, "skills/vgpu");
const committedManifestOut = resolve(root, "packages/vgpu/lib/generated/docs-manifest.generated.js");
const committedContentDir = resolve(root, DEFAULT_CONTENT_DIR);
const REGEN_HINT = "pnpm -F @vgpu/cli generate:docs";
const GEISTDOCS_REGEN_HINT = "node packages/vgpu/lib/docs/generate/generate-geistdocs.js";

const scratch = mkdtempSync(join(tmpdir(), "vgpu-skill-drift-"));
const freshSkillDir = join(scratch, "skills-vgpu");
const freshManifestOut = join(scratch, "docs-manifest.generated.js");
const freshContentDir = join(scratch, "geistdocs-content");

let mismatches;
let contentMismatches;
let generatedFileCount = 0;
try {
  generateDocs({ root, skillDir: freshSkillDir, manifestOut: freshManifestOut });
  mismatches = [
    ...diffManifest(committedManifestOut, freshManifestOut),
    ...diffSkillDir(committedSkillDir, freshSkillDir),
  ];
  // `generateGeistdocs` writes into `freshContentDir` and prunes only inside it; the committed tree
  // is read, never touched.
  const { files } = generateGeistdocs({ root, contentDir: freshContentDir });
  generatedFileCount = files.size;
  contentMismatches = diffGeistdocsContent(committedContentDir, freshContentDir, files);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

let failed = false;

if (mismatches.length > 0) {
  failed = true;
  console.error(
    `::error::skills/vgpu (or the docs manifest) is out of date; run \`${REGEN_HINT}\` and commit the result.`,
  );
  for (const mismatch of mismatches) console.error(`  - ${mismatch}`);
} else {
  console.log("skills/vgpu and the docs manifest match the generator output — no drift.");
}

if (contentMismatches.length > 0) {
  failed = true;
  console.error(
    `::error::${DEFAULT_CONTENT_DIR} is out of date; run \`${GEISTDOCS_REGEN_HINT}\` and commit the result.`,
  );
  for (const mismatch of contentMismatches) console.error(`  - ${mismatch}`);
} else {
  console.log(
    `${DEFAULT_CONTENT_DIR} matches the geistdocs generator output — no drift (${generatedFileCount} generated files).`,
  );
}

if (failed) process.exit(1);

function diffManifest(committedPath, freshPath) {
  const committed = safeRead(committedPath);
  const fresh = safeRead(freshPath);
  if (committed === fresh) return [];
  return [`docs manifest differs from generator output: ${relative(root, committedPath)}`];
}

function diffSkillDir(committedDir, freshDir) {
  const committedFiles = listFiles(committedDir);
  const freshFiles = listFiles(freshDir);
  const issues = [];

  for (const relPath of freshFiles) {
    if (!committedFiles.has(relPath)) issues.push(`missing from skills/vgpu: ${relPath} (generator now produces it)`);
  }
  for (const relPath of committedFiles) {
    if (!freshFiles.has(relPath)) issues.push(`stale file committed in skills/vgpu: ${relPath} (generator no longer produces it)`);
  }
  for (const relPath of committedFiles) {
    if (!freshFiles.has(relPath)) continue;
    const committedContent = safeRead(join(committedDir, relPath));
    const freshContent = safeRead(join(freshDir, relPath));
    if (committedContent !== freshContent) issues.push(`content differs: skills/vgpu/${relPath}`);
  }
  return issues;
}

/**
 * Diffs the committed geistdocs content tree against a freshly generated one.
 *
 * Scope matches what the generator owns, and nothing more (same rule as its own `prune`): generated
 * `.md` pages and `meta.json`. Hand-authored `.mdx` (`content/docs/get-started/**`, TGEIST-11) is
 * NOT generated, so it is invisible here — flagging it as "stale" would demand deleting files the
 * generator was explicitly told never to touch.
 *
 * @param {string} committedDir
 * @param {string} freshDir
 * @param {Map<string, string>} files generated relative path -> contents
 */
function diffGeistdocsContent(committedDir, freshDir, files) {
  const issues = [];
  // `files` keys are already posix-style relative paths; `listFiles` yields platform-native ones, so
  // everything is compared in posix form.
  const generated = new Set([...files.keys()]);
  const toPosix = (relPath) => relPath.split(sep).join("/");

  for (const relPath of generated) {
    const committedContent = safeRead(join(committedDir, relPath));
    if (committedContent === null) {
      issues.push(`missing from ${DEFAULT_CONTENT_DIR}: ${relPath} (the generator produces it)`);
      continue;
    }
    if (committedContent !== safeRead(join(freshDir, relPath))) {
      issues.push(`content differs: ${DEFAULT_CONTENT_DIR}/${relPath}`);
    }
  }

  for (const nativePath of listFiles(committedDir)) {
    const relPath = toPosix(nativePath);
    const owned = relPath.endsWith("meta.json") || (relPath.endsWith(".md") && !relPath.endsWith(".mdx"));
    if (!owned || generated.has(relPath)) continue;
    issues.push(
      `stale generated file committed in ${DEFAULT_CONTENT_DIR}: ${relPath} (the generator no longer produces it)`,
    );
  }

  return issues;
}

function listFiles(dir) {
  const out = new Set();
  const walk = (current) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = join(current, entry.name);
      if (entry.isDirectory()) walk(full);
      else out.add(relative(dir, full));
    }
  };
  if (existsDir(dir)) walk(dir);
  return out;
}

function existsDir(path) {
  try {
    return statSync(path).isDirectory();
  } catch {
    return false;
  }
}

function safeRead(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}
